#!/usr/bin/env python3
"""Builds VARIANTS.md, a review sheet for the 24 erroneous programs.

For each pipeline and each family of errors, the sheet shows the body of
the three versions (PolyFrames, DataFrame, Dataset) next to each other,
together with the outcome expected by the harness and the outcome recorded
in results.csv. It reads the sources and changes none of them.

Usage, from the root of the repository:  python3 scripts/variants-review.py
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VARIANTS = ROOT / "variants"
FAMILIES = [
    ("noattr", "missing attribute"),
    ("badtype", "attribute of an unexpected domain"),
    ("badmodel", "data in the wrong model"),
    ("badtransfo", "transformation breaking the announced model"),
]
BASELINES = [("pf", "PolyFrames"), ("df", "DataFrame"), ("ds", "Dataset")]


def expected():
    """Reads the expected outcome of each variant off Variants.scala."""
    src = (ROOT / "bench/src/main/scala/polyframes/bench/Variants.scala").read_text("utf-8")
    pattern = r'Variant\("([\w-]+)",\s*"\w+",\s*"\w+",\s*variant\("[\w.-]+"\),\s*(true|false)'
    return {name: flag == "true" for name, flag in re.findall(pattern, src)}


def recorded():
    """Reads what results.csv recorded for each variant."""
    out = {}
    with open(ROOT / "results.csv", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["experiment"] == "error-prevention" and row["metric"] in ("compiles", "runs"):
                note = " ".join(row["note"].split())
                if "PolyFrames:" in note:  # the custom message, not the raw implicit
                    note = note[note.index("PolyFrames:"):].rstrip(")")
                if len(note) > 200:
                    note = note[:200] + "…"
                out.setdefault(row["subject"], {})[row["metric"]] = (row["value"], note)
    return out


def body(path):
    """The statements of `main`, without the SparkSession boilerplate."""
    lines = path.read_text("utf-8").splitlines()
    start = next(i for i, l in enumerate(lines) if "def main" in l)
    kept = []
    for l in lines[start + 1:]:
        if "SparkSession.builder" in l or l.strip() in ("try {", "} finally {", "spark.stop()"):
            continue
        kept.append(l)
    while kept and kept[-1].strip() in ("}", ""):
        kept.pop()
    indent = min(len(l) - len(l.lstrip()) for l in kept if l.strip())
    return "\n".join(l[indent:] for l in kept)


def outcome(name, exp, rec):
    r = rec.get(name, {})
    compiles = r.get("compiles", ("?", ""))
    text = f"expected to compile: **{'yes' if exp[name] else 'no'}** · compiled: **{compiles[0]}**"
    if compiles[0] == "false" and compiles[1]:
        text += f"  \n  compiler: `{compiles[1]}`"
    if "runs" in r:
        runs = r["runs"]
        text += f"  \n  ran to completion: **{runs[0]}**"
        if runs[1]:
            text += f" · `{runs[1]}`"
    return text


def main():
    exp, rec = expected(), recorded()
    out = [
        "# Review sheet of the erroneous variants",
        "",
        "Generated by `scripts/variants-review.py` from `variants/` and `results.csv`;"
        " do not edit by hand. For each pipeline and each family, the three versions"
        " should inject the same mistake, on the same attribute, at the same step.",
        "",
    ]
    for pipeline, suffix in (("P1", ""), ("P2", "2")):
        out += [f"## {pipeline}", ""]
        for family, label in FAMILIES:
            out += [f"### {pipeline} · {family} ({label})", ""]
            for prefix, baseline in BASELINES:
                name = f"{prefix}{suffix}-{family}"
                out += [
                    f"**{baseline}** — `variants/{name}.scala` — {outcome(name, exp, rec)}",
                    "",
                    "```scala",
                    body(VARIANTS / f"{name}.scala"),
                    "```",
                    "",
                ]
    (ROOT / "VARIANTS.md").write_text("\n".join(out), "utf-8")


if __name__ == "__main__":
    main()
